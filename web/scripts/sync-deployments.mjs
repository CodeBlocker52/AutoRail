#!/usr/bin/env node
/**
 * One source of truth: copies contracts/deployments/* into web/lib/autorail/generated/ as typed modules.
 *   - deployments.ts   addresses, deploy block, agents, explorer links per chain (44005; 440050 only with SYNC_INCLUDE_FORK=1)
 *   - abis.ts          contract ABIs `as const` (viem infers types)
 *   - recordedRun.ts   the live demo run on Aevum (deployments/demo-run-44005.json)
 *   - labels.ts        address → role label, parsed from contracts/docs/ACCOUNTS.md (addresses only, never keys)
 * Runs in `prebuild`. If ../contracts is absent (e.g. a build rooted at web/), the committed output is kept.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const src = join(web, "..", "contracts", "deployments");
const out = join(web, "lib", "autorail", "generated");
const includeFork = process.env.SYNC_INCLUDE_FORK === "1";

if (!existsSync(join(src, "44005.json"))) {
  console.log("sync-deployments: ../contracts/deployments not found, keeping committed generated files");
  process.exit(0);
}
mkdirSync(out, { recursive: true });
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const header = "// AUTO-GENERATED by web/scripts/sync-deployments.mjs from contracts/deployments. Do not edit.\n";

// ── deployments ──
const chains = [44005, ...(includeFork && existsSync(join(src, "440050.json")) ? [440050] : [])];
const deployments = {};
for (const id of chains) {
  const d = read(join(src, `${id}.json`));
  const c = d.contracts;
  const addr = (n) => c[n].address;
  deployments[id] = {
    chainId: id,
    network: d.network,
    rpc: d.rpc,
    deployBlock: d.deployBlock,
    commit: d.source.commit,
    commitUrl: d.source.commitUrl,
    tUSD8: d.tUSD8,
    admin: d.admin,
    contracts: {
      vault: addr("AutorailVault"),
      registry: addr("ReceivableRegistry"),
      facility: addr("CreditFacility"),
      factory: addr("JobWalletFactory"),
      router: addr("RepaymentRouter"),
      roles: addr("AutorailRoles"),
      identity: addr("IdentityRegistry"),
      reputation: addr("ReputationRegistry"),
      jobWalletImplementation: addr("JobWalletImplementation"),
    },
    deployTxs: Object.fromEntries(Object.entries(c).map(([k, v]) => [k, v.deployTx])),
    agents: d.agents, // slug → ERC-8004 id (ids START AT 0)
  };
}
writeFileSync(
  join(out, "deployments.ts"),
  header +
    `export const DEPLOYMENTS = ${JSON.stringify(deployments, null, 2)} as const;\n\n` +
    `export type DeploymentChainId = keyof typeof DEPLOYMENTS;\n` +
    `export type Deployment = (typeof DEPLOYMENTS)[44005];\n`,
);

// ── ABIs ──
const abiDir = join(src, "abi");
const abiNames = readdirSync(abiDir).filter((f) => f.endsWith(".json")).sort();
let abis = header;
for (const f of abiNames) {
  const name = f.replace(".json", "");
  abis += `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(read(join(abiDir, f)))} as const;\n`;
}
writeFileSync(join(out, "abis.ts"), abis);

// ── recorded run (ordered explicitly; JSON object key order puts "7a" after "12") ──
const RUN_ORDER = ["1", "2", "3", "4", "5", "6", "7a", "7b", "7c", "8", "9", "10a", "10b", "11", "12"];
const run = read(join(src, "demo-run-44005.json"));
const steps = RUN_ORDER.filter((k) => run.steps[k]).map((k) => run.steps[k]);
writeFileSync(
  join(out, "recordedRun.ts"),
  header +
    `export const RECORDED_RUN_ORDER = ${JSON.stringify(RUN_ORDER)} as const;\n` +
    `export const RECORDED_RUN = ${JSON.stringify({ ...run, steps: undefined, orderedSteps: steps }, null, 2)} as const;\n`,
);

// ── address labels (from ACCOUNTS.md: addresses only) ──
const md = readFileSync(join(src, "..", "docs", "ACCOUNTS.md"), "utf8");
const LABEL = {
  DEPLOYER: "Deployer / admin",
  UNDERWRITER: "Autorail Underwriter",
  RELAYER: "Relayer",
  LENDER: "Lender",
  SELLER: "Lumen Data (seller)",
  BUYER: "Frontier Lab (buyer)",
  PAYOUT_SESSION: "Payout agent (session key)",
  MERCHANT: "Kestrel GPU (x402 merchant, demo)",
  ANNOTATOR_A: "Annotator A",
  ANNOTATOR_B: "Annotator B",
  ROGUE: "0xBAD… (injected payee)",
};
const labels = {};
const roles = {};
for (const m of md.matchAll(/\|\s*`([A-Z_]+)`\s*\|\s*\[`(0x[0-9a-fA-F]{40})`\]/g)) {
  labels[m[2].toLowerCase()] = LABEL[m[1]] ?? m[1];
  roles[m[1]] = m[2];
}
writeFileSync(
  join(out, "labels.ts"),
  header +
    `/** Demo role addresses (public). */\nexport const DEMO_ADDRESSES = ${JSON.stringify(roles, null, 2)} as const;\n\n` +
    `/** lower-case address → human label. */\nexport const ADDRESS_LABELS: Record<string, string> = ${JSON.stringify(labels, null, 2)};\n`,
);

// ── demo budgets (recorded + tiny live profile) ──
const demo = read(join(src, "..", "config", "demo.json"));
writeFileSync(join(out, "demoConfig.ts"), header + `export const DEMO_CONFIG = ${JSON.stringify(demo, null, 2)} as const;\n`);

console.log(`sync-deployments: chains [${chains.join(", ")}], ${abiNames.length} ABIs, ${steps.length} recorded steps, ${Object.keys(labels).length} labels`);
